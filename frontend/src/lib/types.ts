/** The shape of docs/data/elections.json, as build.py writes it. */

export interface PartyResult {
  id: string;
  name: string;
  short_name: string;
  /** Zweitstimmen in the Land. */
  votes: number;
  seats: number;
  /** Seats won in a Wahlkreis. */
  wahlkreis: number;
  /** Seats from the Landesliste. */
  list: number;
}

export interface Election {
  /** Bundle key in wahlwerk-data, e.g. de.landtag.st.2026. */
  key: string;
  body: string;
  /** Election day, ISO date. */
  date: string;
  law: { id: string; title: string; citation: string };
  source: {
    publisher: string;
    title: string;
    url: string | null;
    licence: string | null;
    attribution: string | null;
  };
  /** Size of the chamber the engine formed. */
  seats: number;
  /** Valid Zweitstimmen of every party, seated or not. */
  valid_votes: number;
  /** Seated parties, most seats first. */
  parties: PartyResult[];
}

export interface SiteData {
  /** The wahlwerk version that derived the numbers. */
  engine: string;
  elections: Election[];
}

/** One panel of a sketch plate: its art as SVG, its title and caption as text. */
export interface SketchPanel {
  name: string;
  number: number;
  title: string;
  /** The caption's name, then at most two lines of note. */
  caption: string[];
  /** Width and height of the art in px, as drawn. */
  width: number;
  height: number;
  /** The art, an SVG that follows the theme; generated by wahlwerk-ui. */
  svg: string;
  /** Clickable regions over the art (the home plate), in px of the art as drawn. */
  links?: SketchLink[];
}

export interface SketchLink {
  href: string;
  label: string;
  x: number;
  y: number;
  w: number;
  h: number;
}

export interface SketchPlate {
  name: string;
  title: string;
  panels: SketchPanel[];
}

/** The shape of docs/data/sketches.json, as build.py writes it. */
export interface Sketches {
  /** The bundle the numbers in the sketches come from. */
  key: string;
  /** The Wahlbezirk the tally sketches show. */
  unit: string;
  plates: Record<string, SketchPlate>;
  /** The style guide plates of wahlwerk-ui. */
  style: SketchPlate[];
}

/** One BibTeX entry, the fields a reference shows (build.py, references.py). */
export type Reference = Record<string, string | undefined> & { type: string };

/** One statute version: from the engine's law registry, or cited-only (references.py). */
export interface Statute {
  short: string;
  title: string;
  /** The Fassung, as the engine records it. */
  citation: string;
  source: string | null;
  in_force_from?: string | null;
  in_force_until?: string | null;
  /** Whether the engine implements it as a Law. */
  implemented: boolean;
}

export interface DataSource {
  publisher: string;
  title: string;
  url: string | null;
  licence: string | null;
  attribution: string | null;
}

/** docs/data/references.json: the three kinds of source, each from its own home. */
export interface References {
  /** From the engine's docs/references.bib (Zotero), by BibTeX key. */
  literature: Record<string, Reference>;
  /** From the engine's law registry, by law id (one per version). */
  statutes: Record<string, Statute>;
  /** From each bundle's [source], by bundle key. */
  data: Record<string, DataSource>;
}

/** A piece of running text from a wahlwerk.calc docstring (formulas.py). */
export type Segment =
  | { text: string }
  | { strong: string }
  | { math: string }
  | { code: string }
  | { cite: string[] };

/** One block of a module's docstring: a paragraph, a list, a display formula, a table. */
export type Block =
  | { p: Segment[] }
  | { list: Segment[][] }
  | { math: string }
  | { table: { head: Segment[][]; rows: Segment[][][] } };

export interface CalcFunction {
  name: string;
  /** Full dotted name, e.g. wahlwerk.calc.divisor.sainte_lague. */
  qualname: string;
  kind: 'function' | 'class';
  /** The first paragraph of its docstring. */
  summary: Segment[];
}

export interface CalcModule {
  name: string;
  qualname: string;
  title: Segment[];
  body: Block[];
  functions: CalcFunction[];
  /** BibTeX keys, in the order the module cites them. */
  cites: string[];
}

export interface CalcSymbol {
  latex: string;
  meaning: string;
  group: string;
}

/** docs/data/formulas.json: wahlwerk.calc's formulas, read from its docstrings. */
export interface Formulas {
  calc: string;
  symbols: CalcSymbol[];
  layers: { title: string; modules: CalcModule[] }[];
}

/** One step of a protocol, as the engine's flow.protocol_data describes it (laws.json). */
export interface ProtocolStep {
  path: (number | string)[];
  kind: string;
  title: string;
  parameters: [string, string][];
  citation: string | null;
  reads: string[];
  optional_reads: string[];
  writes: string[];
  /** 0 for a step reading only the tally; one more than the latest step it reads from. */
  stage: number;
  /** Positions of the steps at its level it reads from. */
  depends_on: number[];
  holds: string | null;
  /** The models it computes with, outermost first, each down to its formula in wahlwerk.calc. */
  uses: FormulaLink[];
  children: ProtocolStep[];
  /** Top-level steps only: the first and last position it could move to, same result. */
  movable?: [number, number];
}

export interface LawFact {
  fact: string;
  written: string[];
  read: string[];
}

export interface LawData {
  id: string;
  short: string;
  title: string;
  citation: string;
  source: string | null;
  body: string;
  steps: ProtocolStep[];
  facts: LawFact[];
  /** The protocol drawn by wahlwerk-ui, an SVG. */
  drawing: string;
}

/** A model a step computes with and the function in wahlwerk.calc it calls. */
export interface FormulaLink {
  /** Where it sits in the step: method, method.method. */
  field: string;
  kind: string;
  /** Full dotted name, e.g. wahlwerk.calc.plurality.plurality. */
  formula: string;
}

export interface StepKind {
  kind: string;
  /** Full dotted name, e.g. wahlwerk.process.allocation.seats.ApportionSeats. */
  qualname: string;
  summary: Segment[];
  reads: string[];
  writes: string[];
  /** Whether it holds steps of its own (a sequence, a loop). */
  holds: boolean;
  uses: { law: string; short: string; citation: string | null; path: (number | string)[] }[];
  /** What it computes with in the laws shown, each down to its formula. */
  computes: FormulaLink[];
}

/** docs/data/laws.json: the laws the site shows and every kind of step in them. */
export interface Laws {
  laws: LawData[];
  kinds: StepKind[];
}
